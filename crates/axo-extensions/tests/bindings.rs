use std::fmt::Write;
use std::fs;

use axo::ext::{Meta, objects};
use axo::{ErrorCode, SessionEvent, SessionEventKind};

const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../packages/axo-extension-sdk/bindings.ts"
);

fn method(output: &mut String, meta: &Meta, phase: &impl Fn(&str, &str) -> String) {
    if let Some(reason) = meta.skip {
        writeln!(
            output,
            "  // withheld: {} — {}",
            meta.name,
            reason.replace(['\r', '\n'], " ")
        )
        .unwrap();
        return;
    }
    if !meta.doc.is_empty() {
        output.push_str("  /**\n");
        for line in meta.doc.lines() {
            writeln!(output, "   * {}", line.replace("*/", "*\\/")).unwrap();
        }
        output.push_str("   */\n");
    }
    write!(output, "  {}(", meta.name).unwrap();
    if let Some(args_type) = meta.args_type {
        let args_type = phase(args_type, "Deserialize");
        let required = meta
            .params
            .iter()
            .rposition(|param| !param.optional)
            .map_or(0, |i| i + 1);
        for (i, param) in meta.params.iter().enumerate() {
            let optional = if i >= required { "?" } else { "" };
            write!(
                output,
                "{name}{optional}: {args_type}[\"{name}\"], ",
                name = param.name
            )
            .unwrap();
        }
    }
    let result = meta.result_type.map(|name| phase(name, "Serialize"));
    writeln!(
        output,
        "signal?: AbortSignal): Promise<{}>;",
        result.as_deref().unwrap_or("void")
    )
    .unwrap();
}

fn bindings() -> String {
    let types = objects()
        .iter()
        .flat_map(|object| &object.blocks)
        .flat_map(|block| &block.entries)
        .copied()
        .chain(axo_extensions::lifecycle_methods())
        .fold(specta::Types::default(), |types, meta| {
            (meta.register)(types)
        })
        .register::<ErrorCode>()
        .register::<axo::CompletionDetails>()
        .register::<SessionEvent>()
        .register::<SessionEventKind>();
    let types = specta_util::Remapper::new()
        .dangerous_bigints_as_number()
        .remap_types(axo_extensions::wire_types(types));
    let exported = specta_typescript::Typescript::default()
        .export(&types, specta_serde::PhasesFormat)
        .unwrap();
    let mut output = format!(
        "// Generated by cargo test -p axo-extensions --test bindings; do not edit.\n{exported}"
    );
    let phase = |name: &str, suffix: &str| {
        let phased = format!("{name}_{suffix}");
        if exported.contains(&format!("export type {phased} =")) {
            phased
        } else {
            name.to_owned()
        }
    };
    for name in [
        "Credential",
        "DeviceCode",
        "LoginPrompt",
        "LoginSelect",
        "ToolResult",
        "PolicyBlock",
        "PolicyOverride",
        "SpawnReply",
        "SchemeResolution",
    ] {
        writeln!(
            output,
            "export type {name}Input = {};",
            phase(name, "Deserialize")
        )
        .unwrap();
    }
    writeln!(
        output,
        "export type CredentialOutput = {};",
        phase("Credential", "Serialize")
    )
    .unwrap();
    for object in objects().iter().filter(|object| object.name != "types") {
        let mut name = object.name.chars();
        let first = name.next().unwrap().to_uppercase();
        writeln!(output, "\nexport interface {first}{} {{", name.as_str()).unwrap();
        for meta in object.blocks.iter().flat_map(|block| &block.entries) {
            method(&mut output, meta, &phase);
        }
        output.push_str("}\n");
    }
    output.push_str("\nexport interface HostLifecycle {\n");
    for meta in axo_extensions::lifecycle_methods() {
        method(&mut output, meta, &phase);
    }
    output.push_str("}\n");
    output
}

#[test]
fn bindings_are_current() {
    let fresh = bindings();
    if std::env::var("UPDATE_BINDINGS").as_deref() == Ok("1") {
        fs::write(PATH, fresh).unwrap();
    } else {
        assert!(
            fs::read_to_string(PATH).ok().as_deref() == Some(fresh.as_str()),
            "packages/axo-extension-sdk/bindings.ts is stale; run UPDATE_BINDINGS=1 cargo test -p axo-extensions --test bindings"
        );
    }
}

/// Extensions declare the SDK version they were built for; the bridge checks it against this.
#[test]
fn sdk_version_matches_the_package() {
    let manifest = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../packages/axo-extension-sdk/package.json"
    );
    let package: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(manifest).unwrap()).unwrap();
    assert_eq!(package["version"], axo_extensions::SDK_VERSION);
}
